import type { GeneratedSlot, World } from '../../types/game';

/**
 * Grade 7 is the only hand-authored grade: its levels reference a written bank
 * by id, with generated slots appended. Every other grade is fully generated.
 */

function levelQuestionIds(prefix: string, level: number): string[] {
  return Array.from({ length: 9 }, (_, i) => `${prefix}-l${level}-q${i + 1}`);
}

/**
 * Every grade 7 level ends with three generated questions that reroll on each
 * attempt, so replaying is practice rather than recall of nine memorised
 * answers. Difficulty climbs across the three slots.
 */
function rampedSlots(generatorIds: [string, string, string]): GeneratedSlot[] {
  return [
    { generatorId: generatorIds[0], difficulty: 1 },
    { generatorId: generatorIds[1], difficulty: 2 },
    { generatorId: generatorIds[2], difficulty: 3 },
  ];
}

